create table public.motions (
  id bigint generated by default as identity primary key,
  author_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  proposer text not null check (char_length(proposer) between 1 and 80),
  is_anonymous boolean not null default false,
  supporting_argument text not null check (char_length(supporting_argument) between 1 and 3000),
  created_at timestamptz not null default now()
);

create table public.motion_reactions (
  motion_id bigint not null references public.motions(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  vote smallint not null check (vote in (-1, 1)),
  created_at timestamptz not null default now(),
  primary key (motion_id, user_id)
);

create table public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade
);

alter table public.motions enable row level security;
alter table public.motion_reactions enable row level security;
alter table public.admin_users enable row level security;

create policy "Anyone can read motions"
  on public.motions for select
  to anon, authenticated
  using (true);

create policy "Anonymous users can submit motions"
  on public.motions for insert
  to authenticated
  with check (auth.uid() = author_id);

create policy "Anyone can read reactions"
  on public.motion_reactions for select
  to anon, authenticated
  using (true);

create policy "Users can add their own reactions"
  on public.motion_reactions for insert
  to authenticated
  with check (auth.uid() = user_id);

create policy "Users can change their own reactions"
  on public.motion_reactions for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Admins can read admin membership"
  on public.admin_users for select
  to authenticated
  using (auth.uid() = user_id);

create policy "Admins can delete motions"
  on public.motions for delete
  to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()));
